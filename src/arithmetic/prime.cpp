std::vector<uint64_t> make_alternating_primes(int message_bit,
                                              int ntt_prime_modulus,
                                              int prime_count) {
  std::vector<uint64_t> primes;
  const auto scale = uint64_t(1) << message_bit;

  auto higher_start = scale + 1;
  auto lower_start = scale - 1;

  auto next_higher_candidate =
      find_the_next_prime(higher_start, ntt_prime_modulus);
  auto next_lower_candidate =
      find_the_next_prime(lower_start, ntt_prime_modulus, false);

  bool current_direction =
      next_higher_candidate - scale >= scale - next_lower_candidate;

  int prime_index = 0;
  mpf_t cumulative_scale_value, scale_value, next_prime_value,
      current_deviation_value, search_param_value, two_value;
  mpf_inits(cumulative_scale_value, scale_value, next_prime_value,
            current_deviation_value, search_param_value, two_value, NULL);
  mpf_set_d(cumulative_scale_value, 1.0);
  mpf_set_si(scale_value, scale);
  mpf_set_d(two_value, 2);

  mpz_t search_param_value_int;
  mpz_inits(search_param_value_int, NULL);

  while (primes.size() < prime_count) {
    auto search_start = current_direction ? higher_start : lower_start;
    auto next_prime =
        find_the_next_prime(search_start, ntt_prime_modulus, current_direction);

    mpf_set_d(next_prime_value, next_prime);
    mpf_div(current_deviation_value, scale_value, next_prime_value);

    mpf_mul(cumulative_scale_value, cumulative_scale_value,
            current_deviation_value);
    mpf_pow_ui(cumulative_scale_value, cumulative_scale_value, 2);

    mpf_mul(search_param_value, cumulative_scale_value, scale_value);
    mpf_div(search_param_value, search_param_value, two_value);

    mpz_set_f(search_param_value_int, search_param_value);
    uint64_t search_param = mpz_get_si(search_param_value_int);

    if (current_direction) {
      higher_start = next_prime + 2;
      uint64_t searched = search_param * 2 - 1;
      if (searched < lower_start) {
        lower_start = searched;
      };
    } else {
      lower_start = next_prime - 2;
      uint64_t searched = search_param * 2 + 1;
      if (searched > higher_start) {
        higher_start = searched;
      };
    }

    current_direction = !current_direction;
    primes.push_back(next_prime);
  }

  mpf_clears(next_prime_value, current_deviation_value, search_param_value,
             two_value, cumulative_scale_value, scale_value, NULL);
  mpz_clear(search_param_value_int);

  return primes;
}
