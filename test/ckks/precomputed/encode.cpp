TEST(CKKSEncodePrecomputed, Iron) {
  auto config = desilo::fhe::CKKSConfig::from_tier("iron");
  auto precomputed = desilo::fhe::CKKSPrecomputed(config);

  const int full_level = 2;
  EXPECT_EQ(full_level, precomputed.parameters_.get_full_level());

  std::vector<long double> ckks_scales = {
      1.2089251710943447e+24, 1.2089258196146292e+24, 1.2676506002281213e+30};
  std::vector<double> scale_before_tile = {1099511037950.2373, 549755813888,
                                           1099511627776};
  std::vector<int64_t> log_scale_after_tile = {40, 41, 0};
  std::vector<std::vector<int64_t>> r_mult_scale_after_tile = {
      {841627474949, 72053195991416832, 432341166181056512},
      {354072911868, 583744059401, 144106391982833664, 864682332362113024},
      {325609241726, 51848050862, 1152921499238449153, 0}};

  for (int level = 0; level <= full_level; level++) {
    EXPECT_DOUBLE_EQ(ckks_scales[level], precomputed.get_ckks_scale(level));
    EXPECT_DOUBLE_EQ(scale_before_tile[level],
                     precomputed.get_scale_before_tile(level));
    EXPECT_EQ(log_scale_after_tile[level],
              precomputed.get_log_scale_after_tile(level));

    expect_array_equals(precomputed.get_r_mult_scale_after_tile(level),
                        r_mult_scale_after_tile[level]);
  }
}

