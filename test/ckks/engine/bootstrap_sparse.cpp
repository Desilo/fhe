TEST_P(BootstrapSparseStage, MakeCoeffToSlot) {
  const auto [inner_loop_shift, stage_count, log_slot_count] = GetParam();

  auto config = desilo::fhe::CKKSConfig::for_bootstrap();
  config.log_slot_count_ = log_slot_count;
  auto engine = desilo::fhe::CKKSEngine(config);

  const auto [coeff_to_slot_stage_level, _] =
      engine.get_bootstrap_stage_levels(stage_count);
  auto stages = engine.make_coeff_to_slot_stages(stage_count, inner_loop_shift,
                                                 coeff_to_slot_stage_level);

  ASSERT_EQ(stages.size(), stage_count);

  int stage_level_base = coeff_to_slot_stage_level;
  for (int stage_index = 0; stage_index < stages.size(); stage_index++) {
    auto stage = stages[stage_index];
    auto [expected_inner_loop_count, expected_outer_loop_count] =
        loops[{inner_loop_shift, stage_count, log_slot_count}][stage_index];

    EXPECT_EQ(stage->level_, stage_level_base - stage_index);
    EXPECT_EQ(stage->inner_loop_count_, expected_inner_loop_count);
    EXPECT_EQ(stage->outer_loop_count_, expected_outer_loop_count);
    EXPECT_EQ(stage->inner_loop_deltas_.size(), stage->inner_loop_count_);
    EXPECT_EQ(stage->outer_loop_deltas_.size(), stage->outer_loop_count_);

    for (int delta_index = 0; delta_index < stage->inner_loop_deltas_.size();
         delta_index++) {
      const auto inner_delta =
          inner_deltas[{inner_loop_shift, stage_count, log_slot_count}]
                      [stage_index][delta_index];
      EXPECT_EQ(stage->inner_loop_deltas_[delta_index], inner_delta)
          << "values different at index (" << stage_index << ", " << delta_index
          << ")";
    }

    for (int delta_index = 0; delta_index < stage->outer_loop_deltas_.size();
         delta_index++) {
      const auto outer_delta =
          outer_deltas[{inner_loop_shift, stage_count, log_slot_count}]
                      [stage_index][delta_index];
      EXPECT_EQ(stage->outer_loop_deltas_[delta_index], outer_delta)
          << "values different at index (" << stage_index << ", " << delta_index
          << ")";
    }
  }

  for (auto stage : stages) {
    delete stage;
  }
}

TEST_P(BootstrapSparseStage, MakeSlotToCoeff) {
  const auto [inner_loop_shift, stage_count, log_slot_count] = GetParam();

  auto config = desilo::fhe::CKKSConfig::for_bootstrap();
  config.log_slot_count_ = log_slot_count;
  auto engine = desilo::fhe::CKKSEngine(config);

  const auto [_, slot_to_coeff_stage_level] =
      engine.get_bootstrap_stage_levels(stage_count);
  auto stages = engine.make_slot_to_coeff_stages(stage_count, inner_loop_shift,
                                                 slot_to_coeff_stage_level);

  ASSERT_EQ(stages.size(), stage_count);

  int stage_level_base = slot_to_coeff_stage_level;
  for (int stage_index = 0; stage_index < stages.size(); stage_index++) {
    auto stage = stages[stage_index];

    auto inverse_stage_index = stage_count - 1 - stage_index;
    auto [expected_inner_loop_count, expected_outer_loop_count] =
        loops[{inner_loop_shift, stage_count, log_slot_count}]
             [inverse_stage_index];

    EXPECT_EQ(stage->level_, stage_level_base - stage_index);
    EXPECT_EQ(stage->inner_loop_count_, expected_inner_loop_count);
    EXPECT_EQ(stage->outer_loop_count_, expected_outer_loop_count);
    EXPECT_EQ(stage->inner_loop_deltas_.size(), stage->inner_loop_count_);
    EXPECT_EQ(stage->outer_loop_deltas_.size(), stage->outer_loop_count_);

    for (int delta_index = 0; delta_index < stage->inner_loop_deltas_.size();
         delta_index++) {
      const auto inner_delta =
          inner_deltas[{inner_loop_shift, stage_count, log_slot_count}]
                      [inverse_stage_index][delta_index];
      EXPECT_EQ(stage->inner_loop_deltas_[delta_index], inner_delta)
          << "values different at index (" << stage_index << ", " << delta_index
          << ")";
    }

    for (int delta_index = 0; delta_index < stage->outer_loop_deltas_.size();
         delta_index++) {
      const auto outer_delta =
          outer_deltas[{inner_loop_shift, stage_count, log_slot_count}]
                      [inverse_stage_index][delta_index];
      EXPECT_EQ(stage->outer_loop_deltas_[delta_index], outer_delta)
          << "values different at index (" << stage_index << ", " << delta_index
          << ")";
    }
  }

  for (auto stage : stages) {
    delete stage;
  }
}
