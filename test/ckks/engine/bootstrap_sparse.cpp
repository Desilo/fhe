TEST_P(BootstrapSparse, MakePartialSumDeltas) {
  const auto [log_slot_count, expected_deltas] = GetParam();

  auto config = desilo::fhe::CKKSConfig::for_bootstrap();
  config.log_slot_count_ = log_slot_count;
  auto engine = desilo::fhe::CKKSEngine(config);

  auto deltas = engine.make_partial_sum_deltas();

  expect_vector_equals(deltas, expected_deltas);
}

