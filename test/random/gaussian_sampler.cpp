#ifdef DESILO_FHE_CHECK_HARDCODED
TEST(GaussianSampler, BuildTree) {
  const int security_bits = 128;
  const double sigma = 3.2d;
  const int tree_depth = 5;
  const int tree_size = 31;
  const int chop_count = 2;

  uint64_t tree[tree_size * chop_count];

  desilo::fhe::build_gaussian_sampling_tree(tree, security_bits, sigma,
                                            tree_depth, tree_size, chop_count);

  expect_array_equals(tree, expected, 62);
}
#endif

TEST(GaussianSampler, Construct) {
  auto tree = desilo::fhe::GaussianSamplingTree();

  EXPECT_EQ(tree.security_bits_, 128);
  EXPECT_EQ(tree.sigma_, 3.2);
  EXPECT_EQ(tree.depth_, 5);
  EXPECT_EQ(tree.size_, 31);
  EXPECT_EQ(tree.chop_count_, 2);
  EXPECT_EQ(tree.data_size_, 62);

  expect_array_equals(tree.data_, expected, 62);
}
